#include<iostream>
using namespace std;
class Base{
 int _a; 
 const int _b;//we need Initializer List
 int &_c;////we need Initializer List
 int *_d;
    public:
    Base(int a, const int b, int &c):_a(a),_b(b),_c(c){//Initializer List no default constructor will be generated by compiler
        _d = new int(10);
    };
    

    void display() const{
        cout<<"a: "<<_a<<endl;
        cout<<"b: "<<_b<<endl;
        cout<<"c: "<<_c<<endl;
        cout<<"d: "<<*_d<<endl;
    }
    ~Base(){
        delete _d;
    }
};

class MyClass
{
    int _a;
  public :
    MyClass():_a(0){} //default constructor
    void print()
    {
        cout<<"i am class a"<<endl;
    }
}; 
//complie will give auto generated default constructor if we don't provide any constructor in class.
int main() 
{
    MyClass obj1; //-->1.it will call default constructor
    MyClass arrObj[10]; //-->2.it will call parameterized constructor
    
    arrObj[0].print();
    arrObj[1].print();


    vector<MyClass> myObj(10); //--same like above MyClass arrObj[10];
    myObj[0].print();
    myObj[1].print();
   
    vector<MyClass> myObj1; // it will call default constructor
    myObj1.emplace_back(MyClass()); //-->construct an object directly inside the vector and push_back it to the vector
    myObj1.reserve(10); //-->reserve space for 10 objects in vector
    myObj1[0].print();
    myObj1[1].print();
    myObj.push_back(MyClass());
    myObj[0].print();

   
    //Base Class Initialization in Inheritance
    int a=10,b=10,c=20;
    Base *bobj= new Base(a,b,c);
    bobj->display();
    shared_ptr<Base> bObj1 = make_shared<Base>(a,b,c);
    bobj->display();

    delete bobj;
    return 0;
}
